package relay

import (
	"errors"
	"fmt"
	"net/http"

	"github.com/QuantumNous/new-api/common"
	"github.com/QuantumNous/new-api/dto"
	"github.com/QuantumNous/new-api/relay/channel/volcengine"
	relaycommon "github.com/QuantumNous/new-api/relay/common"
	"github.com/QuantumNous/new-api/relay/helper"
	"github.com/QuantumNous/new-api/service"
	"github.com/QuantumNous/new-api/types"

	"github.com/gin-gonic/gin"
)

func AudioHelper(c *gin.Context, info *relaycommon.RelayInfo) (newAPIError *types.NewAPIError) {
	info.InitChannelMeta(c)

	audioReq, ok := info.Request.(*dto.AudioRequest)
	if !ok {
		return types.NewError(errors.New("invalid request type"), types.ErrorCodeInvalidRequest, types.ErrOptionWithSkipRetry())
	}

	request, err := common.DeepCopy(audioReq)
	if err != nil {
		return types.NewError(fmt.Errorf("failed to copy request to AudioRequest: %w", err), types.ErrorCodeInvalidRequest, types.ErrOptionWithSkipRetry())
	}

	err = helper.ModelMappedHelper(c, info, request)
	if err != nil {
		return types.NewError(err, types.ErrorCodeChannelModelMappedError, types.ErrOptionWithSkipRetry())
	}

	adaptor := GetAdaptor(info.ApiType)
	if adaptor == nil {
		return types.NewError(fmt.Errorf("invalid api type: %d", info.ApiType), types.ErrorCodeInvalidApiType, types.ErrOptionWithSkipRetry())
	}
	adaptor.Init(info)

	ioReader, err := adaptor.ConvertAudioRequest(c, info, *request)
	if err != nil {
		return types.NewError(err, types.ErrorCodeConvertRequestFailed, types.ErrOptionWithSkipRetry())
	}

	resp, err := adaptor.DoRequest(c, info, ioReader)
	if err != nil {
		return types.NewOpenAIError(err, types.ErrorCodeDoRequestFailed, http.StatusInternalServerError)
	}
	statusCodeMappingStr := c.GetString("status_code_mapping")

	var httpResp *http.Response
	if resp == nil && volcengine.UsesNativeTTSWebSocket(info) {
		// The native Volc TTS adaptor performs its single provider operation over
		// WebSocket in DoResponse and intentionally has no HTTP response.
	} else {
		httpResp, newAPIError = optionalHTTPResponse(resp)
		if newAPIError != nil {
			return newAPIError
		}
		if httpResp.StatusCode != http.StatusOK {
			newAPIError = service.RelayErrorHandler(c.Request.Context(), httpResp, false)
			// reset status code 重置状态码
			service.ResetStatusCode(newAPIError, statusCodeMappingStr)
			return newAPIError
		}
	}

	usage, newAPIError := adaptor.DoResponse(c, httpResp, info)
	if newAPIError != nil {
		// reset status code 重置状态码
		service.ResetStatusCode(newAPIError, statusCodeMappingStr)
		return newAPIError
	}
	// Adaptors return provider-declared 200 errors before this point. A
	// semantically successful response is accepted exactly once here; adaptors
	// also mark earlier when local delivery fails after accepted audio/ACK data.
	service.MarkUpstreamAccepted(c)
	resolvedUsage, usageErr := acceptedResponseUsage(c, usage)
	if usageErr != nil {
		return usageErr
	}
	if resolvedUsage.CompletionTokenDetails.AudioTokens > 0 || resolvedUsage.PromptTokensDetails.AudioTokens > 0 {
		if billingErr := service.PostAudioConsumeQuota(c, info, resolvedUsage, ""); billingErr != nil {
			return billingErr
		}
	} else {
		if billingErr := service.PostTextConsumeQuota(c, info, resolvedUsage, nil); billingErr != nil {
			return billingErr
		}
	}

	return acceptedResponseDeliveryError(c)
}
